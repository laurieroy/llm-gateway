import os

import streamlit as st
from dotenv import load_dotenv
from streamlit.delta_generator import DeltaGenerator

from multi_provider_llm_gateway import GatewayError
from multi_provider_llm_gateway.pricing import get_model_pricing
from multi_provider_llm_gateway.streaming import (
    StreamMetrics,
    start_stream,
    stream_response,
)

MODEL_OPTIONS = {
    "OpenAI": ["gpt-4o-mini", "gpt-4o"],
    "Anthropic": ["claude-3-5-sonnet", "claude-3-5-haiku"],
}
PROVIDER_API_KEY_ENV_VARS = {
    "OpenAI": "OPENAI_API_KEY",
    "Anthropic": "ANTHROPIC_API_KEY",
}
TELEMETRY_HELP = (
    "Time from sending the request until the first response text arrives, "
    "in milliseconds.",
    "Completion tokens per second, measured after the first token. "
    "During generation this is an estimate.",
    "Tokens in the prompt sent to the model. Estimated while streaming; "
    "provider-reported at completion.",
    "Tokens generated by the model. Estimated while streaming; "
    "provider-reported at completion.",
    "Estimated USD cost from token counts and this app's configured model "
    "rates. Final cost uses provider-reported usage.",
)


def _missing_api_key_environment_variable(provider: str) -> str | None:
    environment_variable = PROVIDER_API_KEY_ENV_VARS[provider]
    return (
        environment_variable
        if not os.getenv(environment_variable, "").strip()
        else None
    )


def _render_stream_error(error: Exception | None) -> None:
    if error is None:
        return
    if isinstance(error, GatewayError):
        st.error(str(error))
        return
    st.error(
        "The request failed unexpectedly. Please check the server logs "
        "and try again."
    )


def _render_dashboard(
    slots: list[DeltaGenerator],
    metrics: StreamMetrics | None = None,
) -> None:
    if metrics is None:
        values = ("—", "—", "—", "—", "—")
        labels = (
            "TTFT",
            "Generation speed",
            "Prompt tokens",
            "Completion tokens",
            "Execution cost",
        )
    else:
        prefix = "~" if metrics.is_estimate else ""
        suffix = " (estimate)" if metrics.is_estimate else ""
        values = (
            f"{prefix}{metrics.ttft_ms:.0f} ms",
            f"{prefix}{metrics.tokens_per_second:.2f} tokens/s",
            f"{prefix}{metrics.prompt_tokens}",
            f"{prefix}{metrics.completion_tokens}",
            f"{prefix}${metrics.cost_usd:.6f}",
        )
        labels = (
            "TTFT",
            "Generation speed",
            f"Prompt tokens{suffix}",
            f"Completion tokens{suffix}",
            f"Execution cost{suffix}",
        )

    for slot, label, value, help_text in zip(
        slots, labels, values, TELEMETRY_HELP, strict=True
    ):
        slot.metric(label, value, help=help_text)


def main() -> None:
    load_dotenv()
    st.set_page_config(page_title="LLM Gateway", layout="wide")
    st.title("Multi-provider LLM Gateway")
    st.caption("Stream a response and inspect its live generation telemetry.")

    st.sidebar.header("Live telemetry")
    dashboard = [st.sidebar.empty() for _ in range(5)]
    _render_dashboard(dashboard)
    st.sidebar.caption(
        "Streaming metrics are estimates until provider-reported usage arrives. "
        "Cost uses the gateway's configured model pricing."
    )

    provider_column, model_column = st.columns(2)
    with provider_column:
        provider = st.selectbox("Provider", list(MODEL_OPTIONS))
    with model_column:
        model = st.selectbox("Model", MODEL_OPTIONS[provider])

    with st.form("generation_form"):
        prompt = st.text_area(
            "Prompt",
            placeholder="What would you like the model to do?",
            height=180,
        )
        temperature = st.slider(
            "Temperature",
            min_value=0.0,
            max_value=2.0,
            value=0.7,
            step=0.1,
            disabled=provider == "Anthropic",
            help=(
                "Controls variation in the response for OpenAI. Lower values "
                "tend to be more predictable; higher values allow more varied "
                "responses. Anthropic's Messages API does not currently accept "
                "temperature, so this control is disabled for Anthropic."
            ),
        )
        submitted = st.form_submit_button(
            "Generate response", type="primary", width="stretch"
        )

    if not submitted:
        return
    if not prompt.strip():
        st.warning("Enter a prompt before generating a response.")
        return

    missing_api_key = _missing_api_key_environment_variable(provider)
    if missing_api_key is not None:
        st.error(
            f"{provider} API key is not configured. Set `{missing_api_key}` "
            "in your `.env` file or environment, then try again."
        )
        return

    pricing = get_model_pricing(model)
    if pricing is None:
        st.error(f"No pricing is configured for {model}.")
        return

    st.subheader("Response")
    events = start_stream(prompt, model, temperature)
    stream, result = stream_response(
        events,
        prompt,
        model,
        pricing,
        lambda metrics: _render_dashboard(dashboard, metrics),
    )
    st.write_stream(stream)

    _render_stream_error(result.error)
    if result.error is None and result.telemetry is None:
        st.error("The stream ended without final usage telemetry.")


if __name__ == "__main__":
    main()
